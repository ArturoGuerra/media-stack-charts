#!/usr/bin/env bash
# Generates CHARTS.md: the current chart version and image of every chart,
# for handing off to agents that upgrade the releases running in the cluster.
# Usage: scripts/gen-charts-md.sh [chart ...]   (run from the repo root)
set -euo pipefail

charts=("$@")
if [[ ${#charts[@]} -eq 0 ]]; then
  read -ra charts <<<"$(sed -n 's/^CHARTS := //p' Makefile)"
fi

field() { sed -n "s/^$1: *//p" "$2" | tr -d '"' | head -1; }

# Prints "repository tag" for the first image block (or the one at the given
# indent) in a values file; tag is empty when it defaults to appVersion.
image_of() {
  awk -v ind="$2" '
    $0 ~ "^" ind "image:" { inimg = 1; next }
    inimg && $1 == "repository:" { repo = $2 }
    inimg && $1 == "tag:" { tag = $2; gsub(/"/, "", tag); print repo, tag; exit }
  ' "$1"
}

{
  echo "# Charts"
  echo
  echo "Current chart versions and the images they deploy. Generated by"
  echo "\`make charts-md\`; do not edit by hand."
  echo
  echo "Image tag defaults to the chart \`appVersion\` when \`values.image.tag\`"
  echo "is empty. Charts shown as \`latest\` float and pick up new app releases on"
  echo "pod restart (most use \`pullPolicy: Always\`); bumping them needs no chart change."
  echo
  echo "| Chart | Chart version | App version | Image |"
  echo "|---|---|---|---|"
  for c in "${charts[@]}"; do
    version=$(field version "$c/Chart.yaml")
    app=$(field appVersion "$c/Chart.yaml")
    read -r repo tag <<<"$(image_of "$c/values.yaml" "")"
    image="\`$repo:${tag:-$app}\`"
    if [[ $c == tdarr ]]; then
      read -r nrepo ntag <<<"$(image_of "$c/values.yaml" "    ")"
      image+="<br>\`$nrepo:${ntag:-$app}\` (workers)"
    fi
    echo "| $c | $version | $app | $image |"
  done
  echo
  echo "## Upgrading a release"
  echo
  echo "Keep the release's existing values; only the chart version changes:"
  echo
  echo '```sh'
  echo 'helm upgrade <release> <repo>/<chart> --version <chart version> -n <namespace> --reuse-values'
  echo '```'
  echo
  echo "Check the deployed version first with \`helm list -A\`. Back up app config"
  echo "before any upgrade marked as a major app version in CHANGELOG.md or the"
  echo "commit history."
} > CHARTS.md

echo "wrote CHARTS.md (${#charts[@]} charts)"
